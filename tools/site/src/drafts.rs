//! The drafts site's gate.
//!
//! A Cloudflare Pages advanced-mode worker for the drafts build. The site sits
//! behind Cloudflare Access (GitHub login); this worker checks Access's signed
//! JWT on every request as a second lock, so the drafts stay closed even if the
//! Access application is missing or misconfigured. The team name comes from
//! $DRAFTS_ACCESS_TEAM (without it the worker refuses everything); the
//! application's audience tag from $DRAFTS_ACCESS_AUD narrows it further.
//! Pages never serves _worker.js itself.

use std::fs;
use std::path::Path;

use anyhow::Result;

const WORKER: &str = r#"// Generated by `cargo site build --drafts`. Cloudflare Access check for the drafts site.
const TEAM = __TEAM__;  // <team>.cloudflareaccess.com
const AUD = __AUD__;    // Access application audience (AUD) tag; optional, see below
const EXTRA = {
  "Cross-Origin-Opener-Policy": "same-origin",
  "Cross-Origin-Embedder-Policy": "require-corp",
  "X-Robots-Tag": "noindex, nofollow",
  "Cache-Control": "private, no-store",
};
let keys = null, keysAt = 0;
async function getKeys() {
  if (keys && Date.now() - keysAt < 3600e3) return keys;
  const r = await fetch(`https://${TEAM}.cloudflareaccess.com/cdn-cgi/access/certs`);
  if (!r.ok) throw new Error("certs " + r.status);
  const { keys: jwks } = await r.json();
  keys = {};
  for (const k of jwks) {
    keys[k.kid] = await crypto.subtle.importKey("jwk", k, { name: "RSASSA-PKCS1-v1_5", hash: "SHA-256" }, false, ["verify"]);
  }
  keysAt = Date.now();
  return keys;
}
const b64u = s => Uint8Array.from(atob(s.replace(/-/g, "+").replace(/_/g, "/")), c => c.charCodeAt(0));
async function allowed(request) {
  if (!TEAM) return false;
  const jwt = request.headers.get("Cf-Access-Jwt-Assertion");
  if (!jwt) return false;
  const parts = jwt.split(".");
  if (parts.length !== 3) return false;
  try {
    const header = JSON.parse(new TextDecoder().decode(b64u(parts[0])));
    const claims = JSON.parse(new TextDecoder().decode(b64u(parts[1])));
    if (header.alg !== "RS256") return false;
    const key = (await getKeys())[header.kid];
    if (!key) return false;
    const ok = await crypto.subtle.verify("RSASSA-PKCS1-v1_5", key, b64u(parts[2]), new TextEncoder().encode(parts[0] + "." + parts[1]));
    if (!ok) return false;
    const aud = Array.isArray(claims.aud) ? claims.aud : [claims.aud];
    const now = Date.now() / 1000;
    // Without an AUD tag, any token signed by this team's Access is accepted:
    // only people its policies let in can get one.
    return (!AUD || aud.includes(AUD)) && claims.iss === `https://${TEAM}.cloudflareaccess.com` && claims.exp > now;
  } catch {
    return false;
  }
}
export default {
  async fetch(request, env) {
    if (!(await allowed(request))) {
      return new Response(TEAM ? "Drafts are private. Sign in through Cloudflare Access." : "Drafts are not set up yet (no Cloudflare Access team).", {
        status: 403,
        headers: { "Content-Type": "text/plain; charset=utf-8", ...EXTRA },
      });
    }
    const r = await env.ASSETS.fetch(request);
    const out = new Response(r.body, r);
    for (const [k, v] of Object.entries(EXTRA)) out.headers.set(k, v);
    return out;
  },
};
"#;

pub fn write_gate(dist: &Path) -> Result<()> {
    let var = |k| std::env::var(k).unwrap_or_default().trim().to_string();
    let team = var("DRAFTS_ACCESS_TEAM");
    let team = team.strip_suffix(".cloudflareaccess.com").unwrap_or(&team).to_string();
    let aud = var("DRAFTS_ACCESS_AUD");
    let worker =
        WORKER.replace("__TEAM__", &serde_json::to_string(&team)?).replace("__AUD__", &serde_json::to_string(&aud)?);
    fs::write(dist.join("_worker.js"), worker)?;
    fs::write(dist.join("robots.txt"), "User-agent: *\nDisallow: /\n")?;
    if team.is_empty() {
        println!("drafts: Access check LOCKED (DRAFTS_ACCESS_TEAM not set)");
    } else {
        let tag = if aud.is_empty() { "no" } else { "with" };
        println!("drafts: Access check on (team {team}, {tag} AUD tag)");
    }
    Ok(())
}
